"""Run the small-E stress simulation.

This script is the publication driver for the deliberately hard
``E=2, p=8, k=5, m=2`` configuration. It uses Gaussian samples only and computes
both:

* the usual AnchorPCA_infty first empirical agreement-block recovery metrics; and
* the Gaussian FindS_star estimate of ``m = dim(S*)``.

The distribution draws must already exist in the bank generated by
``generate_design_bank.py``. The default sample-size grid extends to 100000
observations per domain/environment because this small-E geometry has a very
small population agreement-separation gap.
"""

