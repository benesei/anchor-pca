DEFAULT_SEED = 43
DEFAULT_N_GRID = (50, 100, 200, 500, 1000, 2000, 5000, 10000, 30000, 100000)
DEFAULT_PROFILES = ("balanced", "threshold_stress")
DEFAULT_SAMPLE_REPS = 20
DEFAULT_ALPHA = 0.05
BASE_CONFIG = (2, 8, 5, 2)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run Gaussian small-E AnchorPCA_infty stress simulation."
    )
    parser.add_argument(
        "--design-bank-dir",
        type=Path,
        default=SCRIPT_DIR / "results" / "design_bank",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=SCRIPT_DIR / "results" / "infty_sstar_recovery_g2_low_environment_stress",
    )
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--n-grid", type=int, nargs="+", default=list(DEFAULT_N_GRID))
    parser.add_argument("--sample-reps", type=int, default=DEFAULT_SAMPLE_REPS)
    parser.add_argument(
        "--profiles",
        nargs="+",
        default=list(DEFAULT_PROFILES),
        choices=["balanced", "threshold_stress"],
    )
    parser.add_argument("--alpha", type=float, default=DEFAULT_ALPHA)
    parser.add_argument(
        "--max-designs",
        type=int,
        default=None,
        help="Limit number of stored distribution draws per code-level profile config.",
    )
    parser.add_argument(
        "--skip-seqtest",
        action="store_true",
        help="Only compute AnchorPCA_infty recovery metrics; skip FindS_star diagnostics.",
    )
    parser.add_argument("--overwrite", action="store_true")
    return parser.parse_args()


def default_config_ids(profiles: list[str]) -> list[str]:
    g, p, k, m = BASE_CONFIG
    return [f"{profile}_g{g}_p{p}_k{k}_m{m}" for profile in profiles]


def format_float_array(values: np.ndarray) -> str:
    values = np.asarray(values, dtype=float)
    return ";".join(f"{value:.17g}" for value in values)


def format_int_array(values: np.ndarray) -> str:
    values = np.asarray(values, dtype=int)
    return ";".join(str(int(value)) for value in values)


def sequential_test_metrics(
    *,
    X_envs: list[np.ndarray],
    k: int,
    m: int,
    alpha: float,
    enabled: bool,
) -> dict[str, float | int | str]:
    if not enabled:
        return {
            "m_hat_seqtest": np.nan,
            "r_hat_seqtest": np.nan,
            "dim_correct_seqtest": np.nan,
            "seqtest_failed": 0,
            "seqtest_n_tests": 0,
            "seqtest_min_p_value": np.nan,
            "seqtest_stop_p_value": np.nan,
            "seqtest_tested_s": "",
            "seqtest_p_values": "",
            "seqtest_statistics": "",
            "seqtest_error": "",
        }

    try:
        result = estimate_sstar_dimension(
            X_envs,
            k,
            alpha=alpha,
            assume_gaussian=True,
        )
    except Exception as exc:  # Keep the raw table complete for numerical failures.
        return {
            "m_hat_seqtest": -1,
            "r_hat_seqtest": -1,
            "dim_correct_seqtest": 0,
            "seqtest_failed": 1,
            "seqtest_n_tests": 0,
            "seqtest_min_p_value": np.nan,
            "seqtest_stop_p_value": np.nan,
            "seqtest_tested_s": "",
            "seqtest_p_values": "",
            "seqtest_statistics": "",
            "seqtest_error": f"{type(exc).__name__}: {exc}",
        }

    return {
        "m_hat_seqtest": int(result.m_hat),
        "r_hat_seqtest": int(result.r_hat),
        "dim_correct_seqtest": int(result.m_hat == m),
        "seqtest_failed": 0,
        "seqtest_n_tests": int(result.tested_s.size),
        "seqtest_min_p_value": (
            float(np.min(result.p_values)) if result.p_values.size else np.nan
        ),
        "seqtest_stop_p_value": (
            float(result.p_values[-1]) if result.p_values.size else np.nan
        ),
        "seqtest_tested_s": format_int_array(result.tested_s),
        "seqtest_p_values": format_float_array(result.p_values),
        "seqtest_statistics": format_float_array(result.statistics),
        "seqtest_error": "",
    }


def seqtest_subspace_metrics(
    *,
    barPi: np.ndarray,
    sstar_projector: np.ndarray,
    m_hat: float | int,
) -> dict[str, float]:
    if not np.isfinite(float(m_hat)) or int(m_hat) < 0:
        return {"seqtest_top_m_projector_error_op": np.nan}

    p = int(barPi.shape[0])
    m_hat_int = int(m_hat)
    if m_hat_int == 0:
        projector = np.zeros((p, p), dtype=float)
    elif m_hat_int >= p:
        projector = np.eye(p)
    else:
        _, vectors = eig_desc(barPi)
        projector = projector_from_basis(vectors[:, :m_hat_int])

    return {
        "seqtest_top_m_projector_error_op": projector_metric_norm(
            projector - np.asarray(sstar_projector, dtype=float)
        )
    }


def summarize_seqtest_results(raw: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    group_cols = [
        "config_id",
        "profile",
        "distribution",
        "g",
        "p",
        "k",
        "m",
        "q",
        "N",
        "design_replicate",
    ]
    aggregations = {
        "dim_correct": ["mean", "median"],
        "m_hat_first_block": ["mean", "median"],
        "first_block_projector_error_op": ["mean", "median"],
        "dim_correct_seqtest": ["mean", "median"],
        "m_hat_seqtest": ["mean", "median"],
        "seqtest_top_m_projector_error_op": ["mean", "median"],
        "seqtest_failed": ["mean", "median"],
        "sample_seed": "count",
    }
    by_design = raw.groupby(group_cols, sort=False).agg(aggregations)
    by_design.columns = [
        "_".join(part for part in column if part) for column in by_design.columns
    ]
    by_design = by_design.rename(columns={"sample_seed_count": "n_runs"}).reset_index()

    curve_group_cols = [
        "config_id",
        "profile",
        "distribution",
        "g",
        "p",
        "k",
        "m",
        "q",
        "N",
    ]
    rows = []
    for key, group in by_design.groupby(curve_group_cols, sort=False):
        row = dict(zip(curve_group_cols, key))
        row["n_designs"] = int(len(group))
        row["n_runs"] = int(group["n_runs"].sum())
        for source, prefix in [
            ("dim_correct_mean", "first_block_dim_correct"),
            ("m_hat_first_block_median", "first_block_m_hat"),
            ("first_block_projector_error_op_median", "first_block_projector_error_op"),
            ("dim_correct_seqtest_mean", "seqtest_dim_correct"),
            ("m_hat_seqtest_median", "seqtest_m_hat"),
            ("seqtest_top_m_projector_error_op_median", "seqtest_top_m_projector_error_op"),
            ("seqtest_failed_mean", "seqtest_failed"),
        ]:
            values = group[source].astype(float)
            row[f"{prefix}_mean"] = float(values.mean())
            row[f"{prefix}_q10"] = float(values.quantile(0.10))
            row[f"{prefix}_median"] = float(values.median())
            row[f"{prefix}_q90"] = float(values.quantile(0.90))
        rows.append(row)

    by_curve = pd.DataFrame(rows).sort_values(curve_group_cols).reset_index(drop=True)
    return by_design, by_curve


def write_metadata(
    *,
    output_dir: Path,
    args: argparse.Namespace,
    config_ids: list[str],
    raw_rows: int,
) -> None:
    metadata = {
        "script": repo_relative_path(__file__),
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "software_versions": software_versions(),
        "seed": int(args.seed),
        "design_bank_dir": repo_relative_path(args.design_bank_dir),
        "config_ids": config_ids,
        "base_config": {"g": 2, "p": 8, "k": 5, "m": 2},
        "distribution": "gaussian",
        "n_grid": [int(value) for value in args.n_grid],
        "sample_reps": int(args.sample_reps),
        "alpha": float(args.alpha),
        "max_designs": args.max_designs,
        "findsstar_enabled": not bool(args.skip_seqtest),
        "sequential_test_enabled": not bool(args.skip_seqtest),
        "raw_rows": int(raw_rows),
        "note": (
            "This small-E stress run is Gaussian-only. FindS_star is reported "
            "only under this Gaussian calibration."
        ),
    }
    (output_dir / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")


def main() -> None:
    args = parse_args()
    if any(int(value) <= 1 for value in args.n_grid):
        raise ValueError("All --n-grid values must be greater than one.")
    if args.sample_reps <= 0:
        raise ValueError("--sample-reps must be positive.")
    if not (0.0 < float(args.alpha) < 1.0):
        raise ValueError("--alpha must lie in (0, 1).")
    if args.max_designs is not None and args.max_designs <= 0:
        raise ValueError("--max-designs must be positive when supplied.")

    design_bank_dir = args.design_bank_dir.resolve()
    output_dir = args.output_dir.resolve()
    prepare_output_dir(output_dir, overwrite=bool(args.overwrite))

    design_summary = read_design_summary(design_bank_dir)
    config_ids = default_config_ids(list(args.profiles))
    validate_requested_configs(design_summary, config_ids)

    raw_rows = []
    for config_id in config_ids:
        config = config_metadata(design_summary, config_id)
        arrays = load_config_arrays(design_bank_dir, config_id)
        n_designs_available = int(arrays["covariances"].shape[0])
        n_designs = (
            min(n_designs_available, int(args.max_designs))
            if args.max_designs is not None
            else n_designs_available
        )
        print(
            f"Running {config_id}: {n_designs} designs, "
            f"N={list(args.n_grid)}, distribution=gaussian, "
            f"FindS_star={not bool(args.skip_seqtest)}"
        )
        for design_replicate in range(n_designs):
            population_diagnostics = population_diagnostics_for_design(
                design_summary,
                config_id=config_id,
                design_replicate=design_replicate,
            )
            covariances = np.asarray(arrays["covariances"][design_replicate], dtype=float)
            for n_obs in args.n_grid:
                for sample_replicate in range(int(args.sample_reps)):
                    sample_seed = stable_seed(
                        int(args.seed),
                        config_id,
                        "gaussian",
                        design_replicate,
                        int(n_obs),
                        sample_replicate,
                    )
                    rng = np.random.default_rng(sample_seed)
                    X_envs = sample_environments(
                        rng=rng,
                        covariances=covariances,
                        n_obs=int(n_obs),
                        distribution="gaussian",
                        mean_scale=0.0,
                        w_low=0.5,
                        w_high=2.0,
                    )
                    anchor_metrics, model = empirical_run_metrics_and_model(
                        X_envs=X_envs,
                        arrays=arrays,
                        config=config,
                        design_replicate=design_replicate,
                    )
                    seq_metrics = sequential_test_metrics(
                        X_envs=X_envs,
                        k=int(config["k"]),
                        m=int(config["m"]),
                        alpha=float(args.alpha),
                        enabled=not bool(args.skip_seqtest),
                    )
                    seq_subspace_metrics = seqtest_subspace_metrics(
                        barPi=model.barPi_,
                        sstar_projector=np.asarray(
                            arrays["sstar_projectors"][design_replicate],
                            dtype=float,
                        ),
                        m_hat=seq_metrics["m_hat_seqtest"],
                    )
                    raw_rows.append(
                        {
                            **config,
                            "distribution": "gaussian",
                            "design_replicate": int(design_replicate),
                            "sample_replicate": int(sample_replicate),
                            "N": int(n_obs),
                            "sample_seed": int(sample_seed),
                            **population_diagnostics,
                            **anchor_metrics,
                            **seq_metrics,
                            **seq_subspace_metrics,
                        }
                    )

    raw = pd.DataFrame(raw_rows)
    design_anchor, curve_anchor = summarize_results(raw)
    raw.to_csv(output_dir / "raw_runs.csv", index=False)
    design_anchor.to_csv(output_dir / "summary_by_design.csv", index=False)
    curve_anchor.to_csv(output_dir / "summary_by_curve.csv", index=False)

    if not bool(args.skip_seqtest):
        design_seq, curve_seq = summarize_seqtest_results(raw)
        design_seq.to_csv(output_dir / "summary_by_design_seqtest.csv", index=False)
        curve_seq.to_csv(output_dir / "summary_by_curve_seqtest.csv", index=False)

    write_metadata(
        output_dir=output_dir,
        args=args,
        config_ids=config_ids,
        raw_rows=len(raw),
    )
    print(f"Wrote {len(raw)} raw runs to {output_dir}")


if __name__ == "__main__":
    main()
